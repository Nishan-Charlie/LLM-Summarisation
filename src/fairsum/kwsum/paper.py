"""LaTeX output for the paper: formatted numbers, a macro file of results, booktabs tables.

The paper never types a result by hand. `scripts/kw_paper_assets.py` writes every
number through these helpers into `paper/generated/`, and the text reads them
back with `\\res{key}`, so rerunning the script updates the paper.
"""

from __future__ import annotations

import math
import re

import pandas as pd

_SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
            "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
_KEY = re.compile(r"^[A-Za-z0-9-]+$")


def tex_escape(text: str) -> str:
    return "".join(_SPECIAL.get(ch, ch) for ch in str(text))


def _is_missing(x) -> bool:
    return x is None or (isinstance(x, float) and math.isnan(x))


def fmt(x, digits: int = 3, signed: bool = False, percent: bool = False) -> str:
    """A number as LaTeX text: a typeset minus, an optional plus, "--" when missing."""
    if _is_missing(x):
        return "--"
    value = float(x) * (100 if percent else 1)
    body = f"{abs(value):.{digits}f}"
    suffix = r"\%" if percent else ""
    if float(body) == 0:
        return body + suffix
    if value < 0:
        return "$-$" + body + suffix
    return ("+" if signed else "") + body + suffix


def fmt_ci(estimate, lo, hi, digits: int = 3) -> str:
    return f"{fmt(estimate, digits, signed=True)} [{fmt(lo, digits)}, {fmt(hi, digits)}]"


def fmt_p(p) -> str:
    if _is_missing(p):
        return "--"
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def macro_file(values: dict[str, str]) -> str:
    """`\\res{key}` definitions. Keys are letters, digits and hyphens only."""
    lines = ["% Generated by scripts/kw_paper_assets.py -- do not edit by hand."]
    for key, value in values.items():
        if not _KEY.match(key):
            raise ValueError(f"unsafe macro key {key!r}: use letters, digits and hyphens")
        lines.append(rf"\expandafter\def\csname kw@{key}\endcsname{{{value}}}")
    return "\n".join(lines) + "\n"


def _cell(value) -> str:
    text = "--" if _is_missing(value) else str(value)
    return text if ("$" in text or "\\" in text) else tex_escape(text)


def latex_table(df: pd.DataFrame, caption: str, label: str, align: str | None = None,
                note: str | None = None, size: str = r"\small", star: bool = False,
                colsep: str | None = None) -> str:
    """A floating booktabs table. Cells already written as LaTeX (with $ or \\) are kept as is.
    `colsep` narrows the space between columns for wide tables."""
    env = "table*" if star else "table"
    align = align or "l" * len(df.columns)
    rows = [" & ".join(_cell(c) for c in df.columns) + r" \\"]
    body = [" & ".join(_cell(v) for v in row) + r" \\" for row in df.itertuples(index=False)]
    spacing = [rf"\setlength{{\tabcolsep}}{{{colsep}}}"] if colsep else []
    parts = [rf"\begin{{{env}}}[htbp]", r"\centering", size, *spacing, rf"\caption{{{caption}}}",
             rf"\label{{{label}}}", rf"\begin{{tabular}}{{{align}}}", r"\toprule", *rows,
             r"\midrule", *body, r"\bottomrule", r"\end{tabular}"]
    if note:
        parts += [r"\par\smallskip", rf"\parbox{{\linewidth}}{{\footnotesize {note}}}"]
    parts.append(rf"\end{{{env}}}")
    return "\n".join(parts) + "\n"
